/**
 * fast-json-adapter.js — drop-in replacement for lowdb/node's JSONFile
 * adapter, tuned for a growing db.json under a busy shared write queue
 * (see lib/player-repo.js's runExclusive — every command from either bot
 * number funnels through one db.write() at a time).
 *
 * Two changes from the stock adapter, both purely about write cost, not
 * behavior — read()/write() still do the same job the rest of the code
 * already expects:
 *
 * 1. No pretty-printing. Stock JSONFile does JSON.stringify(data, null, 2)
 *    — the ", null, 2" indents every nesting level for human readability.
 *    Nobody reads db.json by hand at runtime; every indent is bytes that
 *    still have to be generated by V8 and pushed through fs.writeFile for
 *    zero functional benefit. Dropping it cuts both stringify time and
 *    on-disk write size, and since every command from EITHER bot number
 *    waits on this same write finishing (see player-repo.js), a smaller/
 *    faster write directly shortens how long other commands queue behind
 *    it. Pure JSON — still fully valid, still readable with any
 *    formatter/jq if you ever need to inspect it by hand.
 *
 * 2. Atomic write via temp-file + rename. Stock JSONFile writes straight
 *    to db.json. lowdb's own docs note this can corrupt the file if the
 *    process dies mid-write (power loss, OOM kill, a bad pm2 restart
 *    racing a write) — you'd be left with a half-written db.json and
 *    every player's data unreadable on next boot. Writing to a sibling
 *    .tmp file first, then renaming over the real path, means the real
 *    db.json is only ever fully-old or fully-new, never half-written —
 *    rename is atomic on the same filesystem.
 */

import { writeFile, rename } from 'fs/promises'
import { readFileSync, existsSync, copyFileSync } from 'fs'

/**
 * Find the end of the first complete JSON value in a string.
 *
 * A database file that was written by two competing processes can contain
 * two complete JSON documents back-to-back. JSON.parse() rejects that with
 * "Unexpected non-whitespace character after JSON". We only use this scanner
 * after normal parsing fails, and still run JSON.parse() on every candidate so
 * malformed data is never accepted accidentally.
 */
function firstJsonValueEnd(source, start = 0) {
  let i = start
  while (i < source.length && /\s/.test(source[i])) i += 1
  if (i >= source.length) return null

  const first = source[i]
  if (first === '{' || first === '[') {
    const opening = first
    const closing = opening === '{' ? '}' : ']'
    const stack = [closing]
    let inString = false
    let escaped = false

    for (i += 1; i < source.length; i += 1) {
      const char = source[i]
      if (inString) {
        if (escaped) escaped = false
        else if (char === '\\') escaped = true
        else if (char === '"') inString = false
        continue
      }
      if (char === '"') {
        inString = true
      } else if (char === '{') {
        stack.push('}')
      } else if (char === '[') {
        stack.push(']')
      } else if (char === '}' || char === ']') {
        if (stack[stack.length - 1] !== char) return null
        stack.pop()
        if (stack.length === 0) return i + 1
      }
    }
    return null
  }

  if (first === '"') {
    let escaped = false
    for (i += 1; i < source.length; i += 1) {
      const char = source[i]
      if (escaped) escaped = false
      else if (char === '\\') escaped = true
      else if (char === '"') return i + 1
    }
    return null
  }

  // JSON primitives (true, false, null, and numbers) end at whitespace.
  const match = source.slice(i).match(/^(?:true|false|null|-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?)/)
  return match ? i + match[0].length : null
}

function recoverJson(source) {
  let offset = 0
  let lastValue = null
  let recovered = false

  while (offset < source.length) {
    const end = firstJsonValueEnd(source, offset)
    if (end === null) break
    const fragment = source.slice(offset, end)
    try {
      lastValue = JSON.parse(fragment)
      recovered = true
    } catch {
      // A structurally complete fragment that does not parse is not usable.
      break
    }
    offset = end
    while (offset < source.length && /\s/.test(source[offset])) offset += 1
  }

  return recovered ? { value: lastValue } : null
}

export class FastJSONFile {
  constructor(filename) {
    this.filename = filename
    this.tmpFilename = `${filename}.tmp`
  }

  async read() {
    if (!existsSync(this.filename)) return null
    const data = readFileSync(this.filename, 'utf-8')
    if (!data.trim()) return null // matches stock JSONFile: empty file -> null
    try {
      return JSON.parse(data)
    } catch (error) {
      const recovered = recoverJson(data)
      if (!recovered) throw error

      // Keep the original bytes for manual recovery. initDb() calls write()
      // immediately after read(), so the recovered value replaces the bad
      // file atomically on the same boot.
      const backupPath = `${this.filename}.corrupt-${Date.now()}`
      try {
        copyFileSync(this.filename, backupPath)
      } catch {
        // A backup is helpful but must not prevent a valid recovery.
      }

      return recovered.value
    }
  }

  async write(obj) {
    // No ", null, 2" — see file header. Same data, smaller/faster to
    // produce and write; still standard JSON on disk either way.
    const str = JSON.stringify(obj)
    await writeFile(this.tmpFilename, str, 'utf-8')
    await rename(this.tmpFilename, this.filename) // atomic swap
  }
}
